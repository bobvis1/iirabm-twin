"""Write docs/parameter_space.md from config/prior.yaml and docs/results/pilot_summary.json,
so every number in it comes from a result file."""

from __future__ import annotations

import json

from twin.config import DOCS_DIR
from twin.params import DESCRIPTIONS, INT_PARAMS, PARAM_NAMES, Prior

V1_DEFAULTS = {"inj_number": 33, "oxyHeal": 0.1, "infectSpread": 5, "numRecurInj": 2,
               "numInfectRepeat": 2}  # fmt: skip
N_DESIGN = 4096  # proposed library design points (a power of two, so the Sobol design is balanced)
K_SEEDS = 16


def main() -> None:
    prior = Prior.load()
    s = json.loads((DOCS_DIR / "results" / "pilot_summary.json").read_text())
    rows = []
    for n in PARAM_NAMES:
        lo, hi = prior.bounds[n]
        kind = "integers, inclusive" if n in INT_PARAMS else "continuous"
        sp = s["spearman"][n]
        rows.append(
            f"| `{n}` | {DESCRIPTIONS[n]} | {lo:g} to {hi:g} ({kind}) | {V1_DEFAULTS[n]:g} | "
            f"{sp['alive_at_72h']:+.2f} | {sp['alive_at_28d']:+.2f} |"
        )
    cpu_s = s["mean_steps_per_run"] * 1e-3  # 1 ms per step (Phase 1, Apple M4); Phase 3 re-measures
    lib_h = N_DESIGN * K_SEEDS * cpu_s / 3600
    text = f"""# Parameter space, prior and library design

*Generated by `scripts/render_parameter_space.py` from `config/prior.yaml` and
`docs/results/pilot_summary.json`; do not edit by hand. Everything here is for this public 2017
model; the ranges are the ones used in this demonstration, not published or clinical ranges.*

## Prior

Uniform on the box below (`config/prior.yaml`): continuous for `oxyHeal`, uniform over the
integers for the others. The V1 defaults lie inside the box.

| Parameter | Meaning | Range | V1 default | Spearman rho with survival at 72 h | ... at 28 d |
|---|---|---|---|---|---|
{chr(10).join(rows)}

## Pilot sweep

{s["theta"]} random parameter sets drawn from this box x {s["seeds_per_theta"]} seeds ({s["runs"]}
runs of the full 28-day horizon, `engine_fixes` on; `scripts/pilot.py`, `scripts/analyze_pilot.py`).
Figure: `docs/figures/pilot_outcomes.png`.

- Alive at 72 h: **{s["alive_at_72h"]:.0%}** of runs; dead before 72 h: {s["dead_before_72h"]:.0%}.
  Alive at 28 days: {s["alive_at_28d"]:.0%} overall, **{s["alive_at_28d_given_alive_at_72h"]:.0%}** of the runs that were alive at 72 h.
- Almost every run alive at 72 h is sick: only {s["alive72_runs_with_peak_oxy_deficit_below_500"]:.1%} had a peak
  oxy deficit below 500 (so "nobody is ever sick" does not occur), and the high-injury corner is not
  all-dead before 72 h ({s["binned"]["inj_number"]["alive_at_72h"][-1]:.0%} of the highest-injury fifth are still alive at 72 h).
- Outcomes depend mostly on theta, little on the seed: {s["theta_all_seeds_die"]:.0%} of parameter sets killed all
  4 seeds by day 28, {s["theta_all_seeds_survive"]:.0%} spared all 4, and only
  {s["theta_with_mixed_28d_outcomes"]:.0%} gave mixed outcomes. The seed-driven uncertainty at fixed theta is therefore
  concentrated in a minority of the box.
- Which parameters seem to matter: **`inj_number`** most for both time points; `infectSpread` and
  `numInfectRepeat` next; `numRecurInj` weakly. **`oxyHeal` does not affect survival to 72 h
  (rho {s["spearman"]["oxyHeal"]["alive_at_72h"]:+.2f}) but is a strong driver of survival to 28 days
  (rho {s["spearman"]["oxyHeal"]["alive_at_28d"]:+.2f}).** Readings up to the decision time
  (72 h) may therefore say little about `oxyHeal`, the parameter that matters most for the later
  outcome; Phase 5 reports this as posterior contraction.
- The box was kept (not widened) because outcomes still vary at its edges (for example {s["binned"]["inj_number"]["alive_at_28d"][0]:.0%} alive at
  28 days in the lowest-injury fifth). Not explored: `numRecurInj` = 0, `inj_number` < 10,
  `oxyHeal` outside the box.

## Library design

N scrambled Sobol points (fixed scramble seed) over the box, integers by flooring; each point is
simulated with K = {K_SEEDS} library seeds for the full horizon. The posterior is then likelihood
weights on the points (they are a quasi-random sample from the prior, so prior weights are equal).
A lattice is not used (about 5 values per axis at the affordable N). The design can be extended with
the next Sobol points.

**Proposed N = {N_DESIGN}** (a power of two, for balanced Sobol points). Estimated cost: mean
{s["mean_steps_per_run"]:.0f} simulated steps per run in the pilot x 1 ms per step x {K_SEEDS} seeds x {N_DESIGN}
points = about **{lib_h:.0f} CPU-hours** (budget: at most about 100). The step time is the Apple
M4 figure from Phase 1; Phase 3 re-measures it on the SageMaker instance and N is set from that.
"""
    (DOCS_DIR / "parameter_space.md").write_text(text)


if __name__ == "__main__":
    main()
