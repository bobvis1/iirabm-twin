"""Render docs/treatment_report.md and docs/figures/treatment_scores.png from
docs/results/treatment.json (and treatment_jobs.json)."""

from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from twin.config import DOCS_DIR  # noqa: E402
from twin.metrics import wilson  # noqa: E402

R = DOCS_DIR / "results"
ARMS = [("none", "no treatment", "#8a8985"), ("one_size", "one-size-fits-all", "#2a78d6"),
        ("twin", "twin schedule", "#eb6834"), ("oracle", "oracle (true theta)", "#1baf7a")]  # fmt: skip


def f(x, n=2):
    return f"{x:.{n}f}"


def d(x):
    return f"{x['diff']:+.3f} [{x['ci95'][0]:+.3f}, {x['ci95'][1]:+.3f}]"


def figure(t: dict, n: int) -> None:
    pids = list(t["patients"])
    fig, axes = plt.subplots(1, 2, figsize=(14, 4.2), gridspec_kw={"width_ratios": [3, 2]})
    ax = axes[0]
    w = 0.2
    for i, (key, label, col) in enumerate(ARMS):
        m = [t["patients"][p]["mortality"][key] for p in pids]
        err = []
        for p in pids:
            k = round(t["patients"][p]["mortality"][key] * n)
            lo, hi = wilson(k, n)
            err.append(
                (t["patients"][p]["mortality"][key] - lo, hi - t["patients"][p]["mortality"][key])
            )
        ax.bar(np.arange(len(pids)) + (i - 1.5) * w, m, w, color=col, label=label,
               yerr=np.array(err).T, error_kw={"lw": 0.8, "capsize": 2})  # fmt: skip
    ax.set_xticks(np.arange(len(pids)), pids)
    ax.set_ylabel(f"fraction dead by day 28 ({n} fresh futures)")
    ax.set_title("Scored on the true patient (bars: 95% Wilson interval)", fontsize=10)
    ax.legend(frameon=False, fontsize=8, ncol=2, loc="upper center")
    ax.set_ylim(0, 1.2)
    ax = axes[1]
    pred = [
        t["patients"][p]["twin_search"]["no_treatment_cost"]["mortality"]
        - t["patients"][p]["twin_search"]["best_cost"]["mortality"]
        for p in pids
    ]
    real = [
        t["patients"][p]["mortality"]["none"] - t["patients"][p]["mortality"]["twin"] for p in pids
    ]
    ax.plot([0, 0.2], [0, 0.2], color="#8a8985", ls="--", lw=1)
    ax.plot(pred, real, "o", color="#eb6834", ms=8)
    for p, x, y in zip(pids, pred, real, strict=True):
        ax.annotate(
            p.replace("test-", ""), (x, y), textcoords="offset points", xytext=(6, 4), fontsize=8
        )
    ax.set_xlabel("mortality reduction the search found on the twin ensemble")
    ax.set_ylabel("mortality reduction on the true patient")
    ax.set_title("What the twin promised vs what the patient got", fontsize=10)
    ax.grid(alpha=0.25, lw=0.5)
    fig.tight_layout()
    fig.savefig(DOCS_DIR / "figures" / "treatment_scores.png", dpi=140)


def main() -> None:
    t = json.loads((R / "treatment.json").read_text())
    jobs = json.loads((R / "treatment_jobs.json").read_text())
    patients = json.loads((DOCS_DIR.parent / "data" / "treatment" / "patients.json").read_text())
    n = t["futures"]
    figure(t, n)
    rows = []
    for pid, r in t["patients"].items():
        m = r["mortality"]
        rows.append([pid, f(patients_fc(patients, pid)), *[f(m[k]) for k, _, _ in ARMS],
                     d(r["diffs"]["twin_minus_none"]["mortality"]), d(r["diffs"]["twin_minus_one_size"]["mortality"]),
                     d(r["diffs"]["oracle_minus_none"]["mortality"])])  # fmt: skip
    head = [
        "Patient",
        "twin forecast",
        "none",
        "one-size",
        "twin",
        "oracle",
        "twin - none",
        "twin - one-size",
        "oracle - none",
    ]
    tbl = (
        "| "
        + " | ".join(head)
        + " |\n|"
        + "---|" * len(head)
        + "\n"
        + "\n".join("| " + " | ".join(r) + " |" for r in rows)
    )
    pooled = {k: d(v) for k, v in t["schedules"].items()}
    scheds = "\n\n".join(
        f"**{pid}** (twin schedule)\n```\n{r['twin_schedule']}\n```"
        for pid, r in t["patients"].items()
    )
    cost = sum(
        v["estimated_cost_usd"]
        for v in jobs.values()
        if isinstance(v, dict) and "estimated_cost_usd" in v
    )
    text = f"""# Treatment search report (Phase 6)

*Generated by `scripts/render_treatment.py` from `docs/results/treatment.json`; do not edit by hand.
In this model only: a public 2017 agent-based model and virtual patients. The four dials only
resemble approved drugs. **n = {len(t["patients"])} patients and {n} futures each; this is not a clinical result.**
Protocol (fixed before any result): `docs/treatment_protocol.md`.*

## Headline

- A schedule searched on a patient's twin lowered mortality **only for the two patients whose fate was
  open**: test-006 (no treatment {f(t["patients"]["test-006"]["mortality"]["none"])} -> twin schedule {f(t["patients"]["test-006"]["mortality"]["twin"])}) and test-010
  ({f(t["patients"]["test-010"]["mortality"]["none"])} -> {f(t["patients"]["test-010"]["mortality"]["twin"])}); the 95% intervals of the per-patient differences touch or include zero.
- **The twin-personalised schedule did no better than the one-size-fits-all schedule**: identical
  mortality for both informative patients, paired difference {pooled["twin_minus_one_size"]} (pooled over the 5).
  Personalisation added nothing here.
- The oracle (the same search given the *true* parameters) did better ({pooled["oracle_minus_none"]} against
  no treatment), so there was room the twin did not capture.
- **Three of the five chosen patients could not benefit.** The selection rule used only the twin's
  forecast (30-70% mortality), and for test-012, -014 and -015 the true no-treatment mortality was
  {f(t["patients"]["test-012"]["mortality"]["none"], 0)}, {f(t["patients"]["test-014"]["mortality"]["none"], 0)} and {f(t["patients"]["test-015"]["mortality"]["none"], 0)}: their twins were uncertain, the patients were not. The pooled numbers below
  average in those three zeros.

## Results (fraction dead by day 28 on {n} fresh futures of the true patient; paired differences with 95% bootstrap intervals over futures)

{tbl}

Pooled mean over the 5 patients (equal weights; bootstrap over futures with the patients fixed, so it
says nothing about other patients): twin - none {pooled["twin_minus_none"]}; one-size - none {pooled["one_size_minus_none"]};
twin - one-size {pooled["twin_minus_one_size"]}; oracle - none {pooled["oracle_minus_none"]}.

Figure: `docs/figures/treatment_scores.png`. Right panel: for every patient the search found a
mortality reduction on its twin's ensemble (0.04-0.13), including test-012, -014 and -015 where the
true effect is exactly zero, so the reductions a search finds on 32 simulated runs are optimistic.

## What was run

- **Twin search:** ensemble of 8 parameter sets drawn from the patient's posterior x 4 search-range seeds
  (alive at 72 h), GA over 16 genes (population 24, up to 12 generations, early stop), fitness =
  mortality by day 18 then mean oxy deficit + infection.
- **One-size-fits-all:** the same search on an ensemble drawn from the prior:
```
{t["one_size_fits_all"]["schedule"]}
```
- **Twin schedules found:**

{scheds}

- **Scoring:** true parameters and true history seed, reseeded at 72 h with {n} seeds from the future
  range (never used by any search); the history up to 72 h was asserted equal to the stored truth for
  all {sum(r["history_runs_checked"] for r in t["patients"].values())} scored runs. Same futures for every arm.

## Cost (SageMaker, ml.c8i.8xlarge; instance-hours x $1.80, confirm in Cost Explorer)

Twin and one-size-fits-all searches ${jobs["searches_twin_and_one_size_fits_all"]["estimated_cost_usd"]:.2f}, oracle searches ${jobs["searches_oracle"]["estimated_cost_usd"]:.2f}, scoring ${jobs["scoring_1280_runs"]["estimated_cost_usd"]:.2f}, a failed first launch ${jobs["failed_first_attempt"]["estimated_cost_usd"]:.2f}: about ${cost:.2f} in all.

## Limits
- {len(t["patients"])} patients; only two had a fate that treatment could change; intervals are wide and one of the two
  informative patients has a per-patient interval that includes zero.
- The search objective (mortality by day 18 on 32 simulated runs) is a proxy for the scored outcome
  (mortality by day 28 on the true patient), and a search on a small ensemble overfits it.
- The dials, the levels and the model are those of a 2017 public model; nothing here says anything about
  drugs or patients.
"""
    (DOCS_DIR / "treatment_report.md").write_text(text)
    print("wrote docs/treatment_report.md")


def patients_fc(patients: dict, pid: str) -> float:
    return next(x["twin_mortality"] for x in patients["forecasts"] if x["patient"] == pid)


if __name__ == "__main__":
    main()
