"""Write docs/calibration.md from the Phase 4 result files, so every number comes from a file."""

from __future__ import annotations

import json

from twin.config import DOCS_DIR

R = DOCS_DIR / "results"


def f(x, n=2):
    return f"{x:.{n}f}"


def main() -> None:
    t = json.loads((R / "calibration_tuning.json").read_text())
    g = json.loads((R / "ga_tuning.json").read_text())
    job = json.loads((R / "ga_dev_job.json").read_text())
    rows = {r["name"]: r["summary"] for r in t["all"]}
    best = t["best"]
    bs = best["summary"]
    po = t["prior_only"]
    tau1 = rows["synthetic/theta/tau=1.0/tau_run=1.0/floor=0.25"]
    tau3 = rows["synthetic/theta/tau=0.3/tau_run=1.0/floor=0.25"]
    params = list(bs["theta_coverage_by_param"])

    def cov(s):
        return " | ".join(
            f(
                s["theta_coverage_by_param"][p]["0.8"]
                if "0.8" in s["theta_coverage_by_param"][p]
                else s["theta_coverage_by_param"][p][0.8]
            )
            for p in params
        )

    def k(s, d, level):  # coverage dicts have string keys when read back from JSON
        return d.get(str(level), d.get(level))

    def brow(name, s):
        c = " | ".join(f(k(s, s["theta_coverage_by_param"][p], 0.8)) for p in params)
        return (f"| {name} | {c} | {f(k(s, s['forecast_coverage'], 0.8))} | {f(s['brier'], 3)} | "
                f"{s['ess_theta_median']:.0f} / {s['ess_theta_min']:.0f} |")  # fmt: skip

    ga = g["ga_at_best"]
    gl = g["library_on_same_patients"]
    text = f"""# Calibration (Phase 4)

*Generated by `scripts/render_calibration.py` from `docs/results/`; do not edit by hand. Everything is
on the **development cohort** ({t["n_patients"]} patients for the library posterior; the first
{len(g["patients"])} for the GA) in this public 2017 model. No test patient was scored or tuned on.*

## Method

- **Library posterior** (`twin.calibrate.library_posterior`): likelihood weights on the 4,096 design
  points of the simulation library (a quasi-random sample of the prior). A Gaussian synthetic
  likelihood in log1p space with a survival term (the patient is alive at 72 h), measurement noise
  added to the across-run variance, a variance floor, and a **tempering exponent tau** on the reading
  term (the 96 readings are correlated within a run, so counting them as independent is
  overconfident; a toy test with a known answer shows the factor and that tempering by 1/n or the
  run-mixture likelihood fixes it).
- **Prior-only baseline** (`prior_only`): every library run alive at 72 h, equally weighted.
- **GA calibration** (`twin.ga`, `twin.calibrate.ga_calibrate`): population {job["generations"]["min"] and 40}, tournament of 2,
  uniform crossover, one-gene-one-step mutation (as in the lab's 2018 GA design), K = 8 fresh
  simulations of the first 72 h per candidate (fixed seeds: common random numbers), early stop after 5
  generations without improvement; then the best 64 evaluated parameter sets are simulated for the full
  horizon (8 seeds each) to forecast. No library is used.

## Choosing the settings on the development cohort

Two selection rules were used for the library posterior; the first was fixed beforehand and the
**second replaced it after the first run** (both are in `scripts/tune_calibration.py`):

1. *Pooled 80% coverage closest to 80%.* It chose tau = 0.3 (pooled parameter coverage {f(k(tau3, tau3["theta_coverage"], 0.8))}), but
   pooling hid that `inj_number`, the one parameter the readings identify, was covered only
   {f(k(tau3, tau3["theta_coverage_by_param"]["inj_number"], 0.8))} of the time at its 80% interval; the weakly identified parameters were over-covered and pulled the
   pooled number up. Pooled coverage was the wrong criterion.
2. *Rule v2 (used).* No parameter's 80% interval under-covers by more than 0.15, the smallest effective
   sample size is at least 20, then the lowest Brier score. It chose **{best["name"]}**
   (`config/calibration.yaml`).

80% interval coverage by parameter, 28-day-mortality Brier score and effective sample size (median / min), {t["n_patients"]} patients:

| Configuration | {" | ".join(params)} | forecast 80% | Brier | ESS |
|---|---|---|---|---|---|---|---|---|
{brow("prior only", po)}
{brow("tau = 1 (no tempering), theta-level", tau1)}
{brow("tau = 0.3, theta-level", tau3)}
{brow("**chosen**: tau = " + str(best["config"]["tau"]) + ", theta-level", bs)}

With 40 patients the coverage standard error is about 0.06, about 90 configurations were tried, and
the chosen one is optimistic; it is scored once on the test cohort in Phase 5. Posterior variance
over prior variance (mean over patients, chosen config): {", ".join(f"{p} {f(v)}" for p, v in bs["contraction_by_param"].items())}.
Only `inj_number` is clearly identified by readings up to 72 h; `oxyHeal` is not (as the pilot warned).
The 28-day mortality forecast is much better than the baseline (Brier {f(bs["brier"], 3)} against
{f(po["brier"], 3)} prior-only; mean forecast {f(bs["mortality_mean_forecast"])} against observed {f(bs["mortality_observed"])}).
Forecasts over-cover (80% intervals contain the truth {f(k(bs, bs["forecast_coverage"], 0.8))} of the time): conservative.

## GA calibration on {len(g["patients"])} development patients

SageMaker job: {job["instances"]} x `{job["instance_type"]}`, {job["wall_minutes"]} minutes, about
**${job["estimated_cost_usd"]:.2f}**; {job["sims_per_patient"]["median"]:,.0f} simulations per patient (median), {job["generations"]["min"]}-{job["generations"]["max"]} generations,
all {job["stopped_early"]} stopped early.

| Method (same {len(g["patients"])} patients) | {" | ".join(params)} | forecast 80% | Brier |
|---|---|---|---|---|---|---|---|
| library posterior (chosen) | {" | ".join(f(k(gl, gl["theta_coverage_by_param"][p], 0.8)) for p in params)} | {f(k(gl, gl["forecast_coverage"], 0.8))} | {f(gl["brier"], 3)} |
| GA, delta = {g["best_delta"]}, kappa = {g["best_kappa"]} | {" | ".join(f(k(ga, ga["theta_coverage_by_param"][p], 0.8)) for p in params)} | {f(k(ga, ga["forecast_coverage"], 0.8))} | {f(ga["brier"], 3)} |

- **No (delta, kappa) was feasible** under the rule: the GA's parameter intervals are too narrow
  (worst 80% under-coverage {f(g["all_deltas"][0]["max_under80"] if False else min(r["max_under80"] for r in g["all_deltas"]))}). Its evaluated points are an optimiser's trace, not a posterior
  sample, so likelihood weights over them concentrate; tempering them further helped little. The
  pair with the smallest worst under-coverage was used (`config/calibration.yaml`). Treat the GA's
  parameter intervals as approximate; its mortality forecast is as good as the library's.
- Agreement with the library posterior: the two 28-day mortality forecasts correlate at
  {f(g["mortality_forecast_correlation"])} (mean absolute difference {f(g["mean_abs_mortality_difference"], 3)}); the 80% parameter intervals
  overlap (intersection over union) by {", ".join(f"{p} {f(v)}" for p, v in g["mean_interval80_overlap"].items())}.
- Cost: the GA used about {g["sims_per_patient_ga_median"]:,.0f} simulations per patient; the library's {g["sims_library_total"]:,} simulations
  are shared by every patient (and by every future patient), which is why the library is the
  reference method here. The GA is the method that would scale to a parameter space too large for a
  library.

## Honest limits
- The development cohort is small; every number above has a wide error bar.
- Virtual patients and the twin share the same model, prior and noise form (the "inverse crime");
  Phase 5 adds a misspecification stress test.
- The GA's `delta` and `kappa` were chosen on 20 patients with no feasible setting; the GA's
  intervals should not be read as calibrated.
"""
    (DOCS_DIR / "calibration.md").write_text(text)


if __name__ == "__main__":
    main()
